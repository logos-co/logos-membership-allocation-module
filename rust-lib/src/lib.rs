use serde_json::json;

use paymaster_lp as lp;

mod server;

pub trait MembershipAllocationModule: Send + 'static {
    /// Mount the allocation protocol and serve inbound requests. Args
    /// `{config, registries?, authVerifiers?, consumedNullifiersPath?,
    ///  maxRateLimit?, confirmBudgetSec?, advertise?, advertiseAddrs?}` → `{mounted:true,
    ///  registries, advertised, serviceId?, serviceData?, advertisedToPeers?,
    ///  advertisePending?, advertiseError?}`.
    /// Every registration is paid by the registry module's own payer.
    /// authVerifiers maps each accepted authentication_type to its
    /// verifier, `{"<type>": {module?, config?}}`. Without `module` the type
    /// is one this module verifies itself, `<scheme>-<authoriser>` over the
    /// schemes eth, lez, logos, keycard, peer and the authorisers allowlist,
    /// any, attestation (keycard only), pow-claim (logos only), and serve
    /// checks its config. With `module`, that module is asked instead (an
    /// auth_vector VERIFY_METHOD implementor; config rides along opaquely
    /// on every call), for a vector outside that set. No
    /// authVerifiers = an open allocator. advertise (default true) publishes
    /// the served (registry, type) pairs under the protocol id through
    /// libp2p service discovery; a node without discovery mounted serves
    /// unadvertised (advertiseError says so) unless advertise is an explicit
    /// true, which makes that an error. advertiseAddrs (multiaddr strings)
    /// advertises a record signed for those addresses instead of the listen
    /// addresses. The advertisement is placed at once; advertisedToPeers is
    /// the outbound peer count then, and one placed with none is re-placed
    /// once outbound peers appear. confirmBudgetSec (default 150) is how long
    /// a submitted registration may take to show on chain before the request
    /// is answered unconfirmed; the client waits 190 s for the whole
    /// exchange, so a much larger budget outlives it.
    fn serve(&mut self, args_json: String) -> String;
    fn on_context_ready(&mut self, _ctx: &RustModuleContext) {}
}

