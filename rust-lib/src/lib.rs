pub use generated::*;

#[derive(Default)]
struct Allocator {
    server: paymaster_service::ServeState,
}

fn reply(r: Result<serde_json::Value, String>) -> String {
    match r {
        Ok(v) => v.to_string(),
        Err(e) => json!({ "error": e }).to_string(),
    }
}

impl MembershipAllocationModule for Allocator {
    fn serve(&mut self, args_json: String) -> String {
        reply(server::serve(&mut self.server, &args_json))
    }

    fn on_context_ready(&mut self, _ctx: &RustModuleContext) {
        lp::init(&[lp::LIBP2P_MODULE, server::REGISTRY_MODULE]);
    }
}

#[no_mangle]
pub extern "Rust" fn logos_module_install() {
    install::<Allocator>();
}
